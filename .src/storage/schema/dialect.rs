//! Each database server's dialect: its name, how it names a table and a
//! column, the statements that make the roles and each database, and what
//! each kind of column is kept as.
//!
//! **MariaDB** (the owner, 2026-10-12: *Can MariaDB be a contender to
//! PostgreSQL and MSSQL so make it a provider for Storage nodes and create
//! scripts for it*) has no schema inside a database: its schema is its
//! database, so a table is named in the database the script uses, every
//! identifier in backticks. Its tables are `InnoDB`, its text `utf8mb4`
//! compared byte for byte, and it keeps no partial index: an index a row
//! must have a flag for holds every row there, and a search by the flag
//! reads it the same. Its login is refused without TLS (`REQUIRE SSL`).
//!
//! SQL the language — how an identifier is quoted and a literal written —
//! is `xmip-core-library-sql`'s, through each server's [`sql::Dialect`]
//! (ADR-0044, amendment 2026-10-12); what is here is the schema's own: the
//! type each server keeps a column as, its roles, and how a database is
//! made.

use std::fmt::Write as _;

use sql::Dialect;

use super::super::database::Server;
use super::{Database, Kind, LOGIN, OWNER, SCHEMA};

/// The SQL `server` speaks.
const fn language(server: Server) -> &'static Dialect {
    match server {
        Server::PostgreSql => &sql::POSTGRESQL,
        Server::SqlServer => &sql::TSQL,
        Server::MariaDb => &sql::MARIADB,
    }
}

/// The server's name, as its operators know it.
pub(super) const fn name(server: Server) -> &'static str {
    match server {
        Server::PostgreSql => "PostgreSQL",
        Server::SqlServer => "SQL Server",
        Server::MariaDb => "MariaDB",
    }
}

/// `identifier` as `server`'s scripts write it: quoted on MariaDB, where a
/// name the schema gives may be a keyword; bare on PostgreSQL and SQL
/// Server, which take every name the schema gives as it is.
pub(super) fn quoted(server: Server, identifier: &str) -> String {
    match server {
        Server::MariaDb => language(server).quote_identifier(identifier),
        Server::PostgreSql | Server::SqlServer => identifier.to_string(),
    }
}

/// The table `name` as `server`'s scripts name it: in the schema `xmip`,
/// and on MariaDB in the database the script uses.
pub(super) fn table(server: Server, name: &str) -> String {
    match server {
        Server::MariaDb => quoted(server, name),
        Server::PostgreSql | Server::SqlServer => format!("{SCHEMA}.{name}"),
    }
}

/// The login a Storage node connects as, as `server`'s statements name it.
fn login(server: Server) -> String {
    match server {
        Server::MariaDb => {
            let text = |value| language(server).quote_text(value);
            format!("{}@{}", text(LOGIN), text("%"))
        }
        Server::PostgreSql | Server::SqlServer => LOGIN.to_string(),
    }
}

/// The head of every script: what it is, where it comes from, and `run`,
/// where and as whom it is run.
pub(super) fn head(server: Server, what: &str, run: &str) -> String {
    format!(
        "-- Xmip Storage on {}: {what}.\n\
         --\n\
         -- Generated by xmip-core-persist (storage::schema), the definition the\n\
         -- backend reads and writes by; do not edit. `cargo test --test database`\n\
         -- at the estate root fails when this file differs from what it writes.\n\
         -- What to run, in what order and why: README.md beside this file.\n\
         --\n\
         -- {run}\n\n",
        name(server)
    )
}

/// Where and as whom a script making roles or a database is run.
pub(super) const fn run(server: Server) -> &'static str {
    match server {
        Server::PostgreSql => "Run as a superuser, connected to the postgres database.",
        Server::SqlServer => "Run as a sysadmin with sqlcmd.",
        Server::MariaDb => "Run as root with the mariadb client.",
    }
}

/// `01-roles.sql`.
pub(super) fn roles(server: Server) -> String {
    let owner = "-- Owns the schema; no one logs in as it. An operator who changes the\n\
                 -- schema is granted it.\n";
    match server {
        Server::PostgreSql => {
            let mut text = head(server, "the roles", run(server));
            let _ = write!(
                text,
                "{owner}CREATE ROLE {OWNER} NOLOGIN;\n\n\
                 -- The login a Storage node connects as: reads and writes the tables,\n\
                 -- nothing more. Its password is set by the operator, never in a file:\n\
                 -- \\password {LOGIN}\n\
                 CREATE ROLE {LOGIN} LOGIN;\n"
            );
            text
        }
        Server::SqlServer => {
            let mut text = head(
                server,
                "the login",
                "Run as a sysadmin with sqlcmd, its password given as the scripting\n\
                 -- variable StoragePassword (sqlcmd -v StoragePassword=...), never in a file.",
            );
            let _ = write!(
                text,
                "-- The login a Storage node connects as: reads and writes the tables,\n\
                 -- nothing more.\n\
                 CREATE LOGIN {LOGIN} WITH PASSWORD = N'$(StoragePassword)', CHECK_POLICY = ON;\n\
                 GO\n"
            );
            text
        }
        Server::MariaDb => {
            let mut text = head(server, "the roles", run(server));
            let login = login(server);
            let _ = write!(
                text,
                "{owner}CREATE ROLE {OWNER};\n\n\
                 -- The login a Storage node connects as: reads and writes the tables,\n\
                 -- nothing more, over TLS only. It is made locked; the operator sets\n\
                 -- its password and unlocks it, never in a file:\n\
                 -- ALTER USER {login} IDENTIFIED BY '...' ACCOUNT UNLOCK;\n\
                 CREATE USER {login} REQUIRE SSL ACCOUNT LOCK;\n"
            );
            text
        }
    }
}

/// `02-<domain>-database.sql`: the statements that make `database`, on the
/// server that holds it.
pub(super) fn created(server: Server, database: Database) -> String {
    let what = format!("the {} database", database.word());
    let mut text = head(server, &what, run(server));
    let name = quoted(server, database.name());
    let _ = match server {
        Server::PostgreSql => write!(
            text,
            "CREATE DATABASE {name} OWNER {OWNER} ENCODING {} TEMPLATE template0;\n\
             REVOKE ALL ON DATABASE {name} FROM PUBLIC;\n\
             GRANT CONNECT ON DATABASE {name} TO {LOGIN};\n",
            language(server).quote_text("UTF8")
        ),
        Server::SqlServer => write!(
            text,
            "CREATE DATABASE {name};\nGO\n\
             -- Every commit durable before it returns: Xmip counts a write once\n\
             -- the database has it (runtime-model.md section 3).\n\
             ALTER DATABASE {name} SET DELAYED_DURABILITY = DISABLED;\nGO\n"
        ),
        Server::MariaDb => write!(
            text,
            "-- Its text utf8mb4, compared byte for byte, as Xmip compares it.\n\
             CREATE DATABASE {name} CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;\n\
             GRANT ALL PRIVILEGES ON {name}.* TO {OWNER};\n"
        ),
    };
    text
}

/// What opens `03-<domain>-schema.sql`, after its head: the schema made,
/// or the database used.
pub(super) fn schema(server: Server, database: Database) -> String {
    let name = quoted(server, database.name());
    match server {
        Server::PostgreSql => {
            format!("SET ROLE {OWNER};\nCREATE SCHEMA {SCHEMA} AUTHORIZATION {OWNER};\n\n")
        }
        Server::SqlServer => format!(
            "USE {name};\nGO\nCREATE ROLE {OWNER};\nGO\n\
             CREATE SCHEMA {SCHEMA} AUTHORIZATION {OWNER};\nGO\n\n"
        ),
        Server::MariaDb => format!("USE {name};\n\n"),
    }
}

/// What closes `03-<domain>-schema.sql`: the right to read and write the
/// tables, and nothing more, for the login.
pub(super) fn granted(server: Server, database: Database) -> String {
    let name = quoted(server, database.name());
    match server {
        Server::PostgreSql => format!(
            "GRANT USAGE ON SCHEMA {SCHEMA} TO {LOGIN};\n\
             GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {SCHEMA} TO {LOGIN};\n\
             RESET ROLE;\n"
        ),
        Server::SqlServer => format!(
            "CREATE USER {LOGIN} FOR LOGIN {LOGIN};\nGO\n\
             GRANT SELECT, INSERT, UPDATE, DELETE ON SCHEMA::{SCHEMA} TO {LOGIN};\nGO\n"
        ),
        Server::MariaDb => format!(
            "GRANT SELECT, INSERT, UPDATE, DELETE ON {name}.* TO {};\n",
            login(server)
        ),
    }
}

/// What ends a statement making a table or an index: `GO` on SQL Server,
/// `InnoDB` named for a table on MariaDB.
pub(super) const fn ended(server: Server, table: bool) -> &'static str {
    match (server, table) {
        (Server::SqlServer, _) => ";\nGO\n",
        (Server::MariaDb, true) => " ENGINE=InnoDB;\n",
        (Server::PostgreSql | Server::MariaDb, _) => ";\n",
    }
}

/// What a column of `kind` is kept as on `server`.
pub(super) const fn kind(server: Server, kind: Kind) -> &'static str {
    match (server, kind) {
        (Server::PostgreSql, Kind::Identifier) => "uuid",
        (Server::PostgreSql, Kind::Bytes) => "bytea",
        (Server::PostgreSql, Kind::Text | Kind::LongText | Kind::Word) => "text",
        (_, Kind::Number) => "bigint",
        (Server::PostgreSql, Kind::Count) => "integer",
        (Server::PostgreSql | Server::MariaDb, Kind::Flag) => "boolean",
        (Server::PostgreSql, Kind::Sequence) => "bigint GENERATED ALWAYS AS IDENTITY",
        (Server::SqlServer | Server::MariaDb, Kind::Identifier) => "binary(16)",
        (Server::SqlServer, Kind::Bytes) => "varbinary(max)",
        (Server::SqlServer, Kind::Text) => "nvarchar(400)",
        (Server::SqlServer, Kind::LongText) => "nvarchar(max)",
        (Server::SqlServer | Server::MariaDb, Kind::Count) => "int",
        (Server::SqlServer, Kind::Flag) => "bit",
        (Server::SqlServer, Kind::Sequence) => "bigint IDENTITY(1, 1)",
        (Server::PostgreSql, Kind::Time) => "timestamptz",
        (Server::SqlServer, Kind::Time) => "datetime2(7)",
        (Server::SqlServer, Kind::Word) => "nvarchar(32)",
        (Server::MariaDb, Kind::Bytes) => "longblob",
        (Server::MariaDb, Kind::Text) => "varchar(400)",
        (Server::MariaDb, Kind::LongText) => "longtext",
        (Server::MariaDb, Kind::Sequence) => "bigint AUTO_INCREMENT",
        (Server::MariaDb, Kind::Time) => "datetime(6)",
        (Server::MariaDb, Kind::Word) => "varchar(32)",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_name_is_quoted_by_the_sql_library_with_its_delimiter_doubled() {
        assert_eq!(quoted(Server::MariaDb, "in`box"), "`in``box`");
        assert_eq!(quoted(Server::MariaDb, "audit"), "`audit`");
        assert_eq!(quoted(Server::PostgreSql, "audit"), "audit");
        assert_eq!(login(Server::MariaDb), "'xmip_storage'@'%'");
    }
}
